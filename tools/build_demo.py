# -*- coding: utf-8 -*-
"""Build the static Demo into demo/.

Source of truth:
  tools/demo/data/*.json   real LLM outputs (intent, pages, title, hooks, caption)
  frontend/css|js|fonts    renderer, theme tokens, subset fonts

Output:
  demo/index.html          hand-written shell (committed)
  demo/demo.css|demo.js    hand-written UI (committed)
  demo/deck.js             generated from data JSON
  demo/assets/*            copied renderer + fonts + export libs

Run: python tools/build_demo.py
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEMO = ROOT / "demo"
ASSETS = DEMO / "assets"
DATA = ROOT / "tools" / "demo" / "data"

# 内容侧的少量润色（真实数据，不改事实，只改署名/展示长度）
OVERRIDES = {
    "qiuzhao": {
        "id": "qiuzhao",
        "label": "秋招避坑清单",
        "kicker": "清单型 · 7 页",
        "intent": "写一份秋招投递避坑清单：投递前自查、简历、面试跟进三个部分，给 26 届，语气真诚、可收藏",
        "style": "ins",
        "meta": {"author": "小秋", "avatar": "秋", "brand": "@小秋求职笔记"},
        "endingTags": ["秋招", "26届", "求职干货", "避坑清单"],
        "stripQuote": True,
    },
    "team": {
        "id": "team",
        "label": "第一次带团队",
        "kicker": "复盘型 · 8 页",
        "intent": "写一篇第一次带团队的复盘：从自己干到带人交付，三个转折点，语气克制、真诚",
        "style": "literary",
        "meta": {"author": "阿岚", "avatar": "岚", "brand": "@阿岚的管理笔记"},
        "endingTags": ["带团队", "管理转型", "职场复盘", "自我成长"],
        "stripQuote": False,
    },
}

COPIES = [
    ("frontend/css/page.css", "assets/page.css"),
    ("frontend/js/engine.js", "assets/engine.js"),
    ("frontend/js/themes.js", "assets/themes.js"),
    ("frontend/vendor/html-to-image.min.js", "assets/vendor/html-to-image.min.js"),
    ("frontend/vendor/jszip.min.js", "assets/vendor/jszip.min.js"),
    ("tools/demo/vendor/qrcode.min.js", "assets/vendor/qrcode.min.js"),
]


def polish(raw: dict, ov: dict) -> dict:
    data = raw["data"]
    data["meta"] = {**data.get("meta", {}), **ov["meta"]}
    pages = data.get("pages", [])
    if ov["endingTags"]:
        for page in pages:
            if page.get("type") == "ending":
                page["tags"] = ov["endingTags"]
    if ov["stripQuote"]:
        for page in pages:
            if page.get("type") == "quote" and isinstance(page.get("text"), str):
                page["text"] = page["text"].strip().strip("“”\"")
    # 让封面 / 章节的 progress 与真实页数一致
    total = len(pages)
    for i, page in enumerate(pages):
        if page.get("progress"):
            page["progress"] = f"{i + 1:02d} / {total:02d}"
    return {
        "id": ov["id"],
        "label": ov["label"],
        "kicker": ov["kicker"],
        "intent": ov["intent"],
        "style": ov["style"],
        "title": raw.get("title") or "",
        "hooks": raw.get("hooks") or [],
        "caption": raw.get("caption") or "",
        "data": data,
    }


def main() -> int:
    DEMO.mkdir(exist_ok=True)
    ASSETS.mkdir(exist_ok=True)
    (ASSETS / "fonts").mkdir(exist_ok=True)
    (ASSETS / "vendor").mkdir(exist_ok=True)

    decks = []
    for name, ov in OVERRIDES.items():
        raw = json.loads((DATA / f"{name}.json").read_text(encoding="utf-8"))
        decks.append(polish(raw, ov))

    payload = "/* generated by tools/build_demo.py — do not edit */\n"
    payload += "window.XHS_DEMO = " + json.dumps({"decks": decks}, ensure_ascii=False, separators=(",", ":")) + ";\n"
    (DEMO / "deck.js").write_text(payload, encoding="utf-8")

    for src, dst in COPIES:
        target = DEMO / dst
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / src, target)

    fonts_css = (ROOT / "frontend/css/fonts.css").read_text(encoding="utf-8")
    fonts_css = fonts_css.replace("/static/fonts/", "fonts/")
    (ASSETS / "fonts.css").write_text(fonts_css, encoding="utf-8")

    for font in (ROOT / "frontend/fonts").glob("*.woff2"):
        shutil.copyfile(font, ASSETS / "fonts" / font.name)

    print(f"demo built: {len(decks)} decks, {sum(len(d['data']['pages']) for d in decks)} pages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
